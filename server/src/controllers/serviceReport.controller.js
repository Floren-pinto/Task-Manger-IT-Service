import crypto from "node:crypto";
import { asyncHandler } from "../utils/asyncHandler.js";
import { ApiError } from "../utils/ApiError.js";
import { created, ok } from "../utils/ApiResponse.js";
import { isUuid } from "../utils/queryParams.js";
import {
  buildServiceReportSnapshot,
  fetchTaskForSnapshot,
} from "../utils/serviceReportSnapshot.js";

const REPORT_TEXT_MAX_LENGTH = 2000;

const REPORT_LIST_COLUMNS = `id, task_id, created_by_id, summary, action_taken, notes, created_at, updated_at,
  createdBy:users!service_reports_created_by_id_fkey (id, name, email)`;

const REPORT_DETAIL_COLUMNS = `id, task_id, created_by_id, summary, action_taken, notes, snapshot_data, created_at, updated_at,
  createdBy:users!service_reports_created_by_id_fkey (id, name, email)`;

function parseRequiredText(value, field) {
  if (typeof value !== "string" || !value.trim()) {
    throw new ApiError(400, `${field} is required`);
  }

  const text = value.trim();
  if (text.length > REPORT_TEXT_MAX_LENGTH) {
    throw new ApiError(
      400,
      `${field} must be at most ${REPORT_TEXT_MAX_LENGTH} characters`,
    );
  }

  return text;
}

function parseOptionalText(value, field) {
  if (value === undefined || value === null) return null;
  if (typeof value !== "string") {
    throw new ApiError(400, `${field} must be a string`);
  }

  const text = value.trim();
  if (text.length > REPORT_TEXT_MAX_LENGTH) {
    throw new ApiError(
      400,
      `${field} must be at most ${REPORT_TEXT_MAX_LENGTH} characters`,
    );
  }

  return text || null;
}

async function ensureTaskVisible(supabase, taskId) {
  const { data, error } = await supabase
    .from("tasks")
    .select("id")
    .eq("id", taskId)
    .maybeSingle();

  if (error) {
    if (error.code === "22P02") throw new ApiError(400, "Invalid task ID");
    throw new ApiError(500, "Failed to fetch task");
  }
  if (!data) throw new ApiError(404, "Task not found or accessible");
}

export const createTaskReport = asyncHandler(async (req, res) => {
  const { taskId } = req.params;
  const body = req.body ?? {};

  if ("snapshotData" in body || "snapshot_data" in body) {
    throw new ApiError(400, "snapshotData is generated by the server");
  }

  const summary = parseRequiredText(body.summary, "summary");
  const actionTaken = parseRequiredText(body.actionTaken, "actionTaken");
  const notes = parseOptionalText(body.notes, "notes");

  const { data: task, error: taskError } = await fetchTaskForSnapshot(
    req.supabase,
    taskId,
  );

  if (taskError) {
    if (taskError.code === "22P02") throw new ApiError(400, "Invalid task ID");
    throw new ApiError(500, "Failed to fetch task");
  }
  if (!task || task.deleted_at) {
    throw new ApiError(404, "Task not found or accessible");
  }
  if (task.status !== "COMPLETED") {
    throw new ApiError(
      409,
      "Service report can only be created for completed tasks",
    );
  }

  const now = new Date().toISOString();

  const { data, error } = await req.supabase
    .from("service_reports")
    .insert({
      id: crypto.randomUUID(),
      task_id: task.id,
      created_by_id: req.profile.id,
      summary,
      action_taken: actionTaken,
      notes,
      snapshot_data: buildServiceReportSnapshot(task),
      created_at: now,
      updated_at: now,
    })
    .select(REPORT_DETAIL_COLUMNS)
    .single();

  if (error) {
    if (error.code === "42501") {
      throw new ApiError(
        403,
        "You are not allowed to create a service report for this task",
      );
    }
    console.error("Failed to create service report:", error.message);
    throw new ApiError(500, "Failed to create service report");
  }

  return created(res, data, "Service report created");
});

export const listTaskReports = asyncHandler(async (req, res) => {
  const { taskId } = req.params;

  await ensureTaskVisible(req.supabase, taskId);

  const { data, error } = await req.supabase
    .from("service_reports")
    .select(REPORT_LIST_COLUMNS)
    .eq("task_id", taskId)
    .order("created_at", { ascending: false });

  if (error) {
    throw new ApiError(500, "Failed to fetch service reports");
  }

  return ok(res, data ?? []);
});

export const getTaskReport = asyncHandler(async (req, res) => {
  const { taskId, reportId } = req.params;

  if (!isUuid(reportId)) {
    throw new ApiError(400, "Invalid report ID");
  }

  const { data, error } = await req.supabase
    .from("service_reports")
    .select(REPORT_DETAIL_COLUMNS)
    .eq("id", reportId)
    .eq("task_id", taskId)
    .maybeSingle();

  if (error) {
    throw new ApiError(500, "Failed to fetch service report");
  }
  if (!data) throw new ApiError(404, "Service report not found");

  return ok(res, data);
});

